const fs = require('node:fs');
const path = require('node:path');
function loadEnv() {
  const envPath = path.join(__dirname, '../.env');
  if (fs.existsSync(envPath)) {
    const lines = fs.readFileSync(envPath, 'utf8').split('\n');
    for (const line of lines) {
      const match = line.match(/^\s*([\w.-]+)\s*=\s*(.*)?\s*$/);
      if (match) {
        const key = match[1];
        let val = (match[2] || '').trim();
        if (val.startsWith('"') && val.endsWith('"')) val = val.slice(1, -1);
        if (val.startsWith("'") && val.endsWith("'")) val = val.slice(1, -1);
        if (!process.env[key]) process.env[key] = val;
      }
    }
  }
}
loadEnv();

const coreCode = fs.readFileSync(path.join(__dirname, '../n8n/code/whatsapp_conversation_core.generated.js'), 'utf8');

const AsyncFunction = Object.getPrototypeOf(async function () {}).constructor;

let engineModule = null;
async function getEngine() {
  if (engineModule) return engineModule;
  const modifiedCode = coreCode.replace(
    'try {\n  return { json: await runTurn() };',
    'return { salesResolveInventoryItemForFact, salesValidatePrimaryDialogue, salesSanitizeSemanticState, salesNaturalDialogue, normalizeText, salesRecoverSafeDialogue, salesCatalogPresentationProof, salesDialogueFactLedger, salesApplySemanticIntent };\ntry {\n  return { json: await runTurn() };'
  );
  const runner = new AsyncFunction(
    '$json', '$env', '$vars', '$getWorkflowStaticData',
    modifiedCode
  );
  engineModule = await runner.call(
    { helpers: { httpRequest: async () => ({}) } },
    {
      tenant_slug: 'wesley_automoveis', tenant_id: 'tenant-genesis', remoteJid: '5511999999999@s.whatsapp.net', instance: 'genesis-instance',
      noria_preclaimed_turn: { boundary_id: 'b1', messages: [{ id: 'm1', text: 'oi' }] }, noria_business_context: { inventory: [] },
      noria_client_policy: { profile: 'vehicle_sales_v1', capability: 'sales_v1', contract: 'noria_policy_v2', tenant_slug: 'wesley_automoveis', tenant_id: 'tenant-genesis', audio_enabled: false, scheduling_enabled: false },
    },
    process.env,
    {},
    () => ({})
  );
  return engineModule;
}

test('P0 Final Audit 1: Incident Fact Resolution & Unverified/Sold Exclusion', async () => {
  const sandbox = await getEngine();
  const inventory = [
    { id: 'prod_tornado', model: 'TORNADO 300L', brand: 'HONDA', year: 2025, price_cents: 2898000, status: 'announced', offerable: true, category: 'motorcycle' },
    { id: 'prod_pcx2023', model: 'PCX', brand: 'HONDA', year: 2023, price_cents: 1749900, status: 'announced', offerable: true, category: 'motorcycle' },
    { id: 'prod_crosser', model: 'CROSSER', brand: 'YAMAHA', year: 2023, price_cents: 1798000, status: 'announced', offerable: true, category: 'motorcycle' },
    { id: 'prod_cb600rr', model: 'CB 600RR', brand: 'HONDA', year: 2007, price_cents: 3498000, status: 'announced', offerable: true, category: 'motorcycle' },
    { id: 'prod_crosser_sold', model: 'CROSSER', brand: 'YAMAHA', year: 2021, price_cents: 1349900, status: 'sold', offerable: false, category: 'motorcycle' },
    { id: 'prod_pcx2018_unv', model: 'PCX', brand: 'HONDA', year: 2018, price_cents: 1398000, status: 'unverified', offerable: false, category: 'motorcycle' },
  ];

  // 1. salesResolveInventoryItemForFact resolves short slug variants generated by Gemini
  const tornado = sandbox.salesResolveInventoryItemForFact('inv_tornado', inventory);
  assert.ok(tornado, 'inv_tornado should resolve to TORNADO 300L');
  assert.equal(tornado.id, 'prod_tornado');

  const pcx = sandbox.salesResolveInventoryItemForFact('inv_pcx', inventory);
  assert.ok(pcx, 'inv_pcx should resolve');
  assert.equal(pcx.id, 'prod_pcx2023');

  const cb600rr = sandbox.salesResolveInventoryItemForFact('inv_cb600rr', inventory);
  assert.ok(cb600rr, 'inv_cb600rr should resolve');
  assert.equal(cb600rr.id, 'prod_cb600rr');

  const crosser = sandbox.salesResolveInventoryItemForFact('inv_crosser', inventory);
  assert.ok(crosser, 'inv_crosser should resolve');
  assert.equal(crosser.id, 'prod_crosser');

  // 2. Fact validation with multi-attribute claims accepts Gemini's claims on valid inventory
  const generatedValid = {
    primary_reply: 'Temos a Tornado 300L 2025 por R$ 28.980, a PCX 2023 por R$ 17.499, a Crosser 2023 por R$ 17.980 e a CB 600RR 2007 por R$ 34.980.',
    response_contract: {
      answers: [{ request_id: 'req_1', excerpt: 'Temos a Tornado 300L 2025 por R$ 28.980' }],
      requested_fields: [],
      facts: [
        { fact_id: 'inv_tornado', value: '2898000', excerpt: 'Tornado 300L 2025 por R$ 28.980' },
        { fact_id: 'inv_pcx', value: '1749900', excerpt: 'PCX 2023 por R$ 17.499' },
        { fact_id: 'inv_crosser', value: '1798000', excerpt: 'Crosser 2023 por R$ 17.980' },
        { fact_id: 'inv_cb600rr', value: '3498000', excerpt: 'CB 600RR 2007 por R$ 34.980' }
      ],
      availability_asserted: false,
      assignment_confirmed: false,
      photo_sent: false
    }
  };
  const plan = { requests: [{ id: 'req_1', topic: 'catalog' }], next_requirement: 'none', handoff_reason: 'none' };
  const auditValid = sandbox.salesValidatePrimaryDialogue(generatedValid, plan, {}, { inventory });
  assert.equal(auditValid.status, 'accepted', 'Valid dialogue with real inventory should be accepted');
  assert.equal(auditValid.issues.length, 0);

  // 3. Unverified product (PCX 2018 with price 1398000) is rejected as UNSUPPORTED_AMOUNT if unverified
  const generatedUnverified = {
    primary_reply: 'Temos uma PCX 2018 por R$ 13.980.',
    response_contract: {
      answers: [{ request_id: 'req_1', excerpt: 'Temos uma PCX 2018 por R$ 13.980.' }],
      requested_fields: [],
      facts: [
        { fact_id: 'inv_pcx2018', value: '1398000', excerpt: 'PCX 2018 por R$ 13.980' }
      ],
      availability_asserted: false,
      assignment_confirmed: false,
      photo_sent: false
    }
  };
  // Pass offerable stock only (as salesGenerate now does)
  const offerableOnly = inventory.filter(p => p.offerable);
  const auditUnverified = sandbox.salesValidatePrimaryDialogue(generatedUnverified, plan, {}, { inventory: offerableOnly });
  assert.equal(auditUnverified.status, 'needs_human_review', 'Unverified vehicle must be rejected');
  assert.ok(auditUnverified.issues.some(i => i.includes('UNSUPPORTED_AMOUNT:1398000')), 'Must flag UNSUPPORTED_AMOUNT:1398000');
});

test('P0 Final Audit 2: Trade-In Contact (xx) Semantic State & Repetition Prevention', async () => {
  const sandbox = await getEngine();

  // Test 1: Year 2012 / Model 2013 with debts
  const text = 'Ano 2012 \n Modelo 2013 \n 2 anos de documento \n 1.500 de multa';
  const messages = [{ id: 'm1', text, direction: 'inbound' }];
  const state = {
    customer_name: null,
    sell_vehicle: {
      model: 'Modelo 2013', // Model mistakenly placed as year string by naive LLM
      year: 2012,
      model_year: 2013,
      concerns: '2 anos de documento, 1.500 de multa',
      evidence_ids: ['m1'],
      reported_facts: []
    }
  };

  const sanitized = sandbox.salesSanitizeSemanticState(state, messages);
  assert.equal(sanitized.sell_vehicle.year, 2012, 'Year 2012 must be preserved');
  assert.equal(sanitized.sell_vehicle.model_year, 2013, 'Model year 2013 must be preserved');
  assert.equal(sanitized.sell_vehicle.model, '', 'Modelo 2013 must be recognized as year and cleared from model');

  // Test 2: If model is empty but year is already known, do not re-ask year
  const s = {
    customer_name: 'Contato',
    sell_vehicle: {
      year: 2012,
      model_year: 2013,
      model: ''
    }
  };
  // Simulate reply that wrongly re-asks for year and model
  const generatedReplyWithYear = 'Qual é o modelo e o ano do seu carro? E possui multas ou débitos?';
  const normReplyLower = sandbox.normalizeText(generatedReplyWithYear);
  const alreadyHasYear = Boolean(s.sell_vehicle?.year || s.sell_year);
  const missingModel = !s.sell_vehicle?.model && !s.sell_model;
  const reaskingYear = alreadyHasYear && missingModel && /\b(?:qual\s+(?:e\s+)?(?:o\s+)?ano|(?:ano|modelo)\s+e\s+(?:o\s+)?(?:ano|modelo))\b/i.test(normReplyLower);
  assert.ok(reaskingYear, 'Should detect re-asking year when already known');

  let fixedReply = generatedReplyWithYear;
  if (reaskingYear) {
    fixedReply = 'Anotado o ano do seu veículo! Qual é o modelo e marca dele?';
  }
  assert.equal(fixedReply, 'Anotado o ano do seu veículo! Qual é o modelo e marca dele?');
  assert.ok(!/qual\s+(?:e\s+o\s+)?ano/i.test(fixedReply), 'Must not ask for year');
  assert.ok(!fixedReply.includes('multa'), 'Must not re-ask for debts/fines');
});

test('P0 Final Audit 3: POLICY_IS_NOT_OFFER & Appraisal Review Handoff', async () => {
  const sandbox = await getEngine();
  const sessionIds = ['m1'];

  // Test 1: Simple trade-in inquiry ("Vocês aceitam carro na troca?")
  const inquiryPlan = {
    requests: [{ id: 'req_1', topic: 'trade_in' }],
    next_requirement: 'none',
    handoff_reason: 'appraisal_review',
    human_requested: false,
    memory: {
      trade_in_status: 'policy_discussed',
      evidence_ids: ['m1'],
      customer_vehicle_purpose: 'entry_inquiry',
      customer_vehicle_purpose_evidence_ids: ['m1']
    }
  };

  const validated = sandbox.salesNaturalDialogue.validatePlan(inquiryPlan, sessionIds);
  assert.equal(validated.handoff_reason, 'none', 'Simple inquiry should NOT trigger handoff');
  assert.equal(validated.memory.trade_in_status, 'policy_discussed', 'Must NOT fabricate offered status');

  // Test 2: Concrete trade-in offer ("Quero dar meu Gol 2015 de entrada na Crosser")
  const concretePlan = {
    requests: [{ id: 'req_1', topic: 'trade_in' }],
    next_requirement: 'none',
    handoff_reason: 'appraisal_review',
    human_requested: false,
    memory: {
      trade_in_status: 'offered',
      evidence_ids: ['m1'],
      customer_vehicle_purpose: 'entry',
      customer_vehicle_purpose_evidence_ids: ['m1']
    }
  };

  const validatedConcrete = sandbox.salesNaturalDialogue.validatePlan(concretePlan, sessionIds);
  assert.equal(validatedConcrete.handoff_reason, 'appraisal_review', 'Concrete offer should allow appraisal_review');
  assert.equal(validatedConcrete.memory.trade_in_status, 'offered');

  const noPolicyLedger = sandbox.salesDialogueFactLedger(
    { settings: { settings: { business_facts: {} } } }, null, {}, {}, {}, [], [], inquiryPlan
  );
  assert.equal(noPolicyLedger.official.policy.vehicle_trade_in_accepted_subject_to_appraisal, false);
  assert.ok(!noPolicyLedger.facts.some((fact) => fact.id === 'trade_in_policy'));

  const configuredPolicyLedger = sandbox.salesDialogueFactLedger(
    { tenant: { id: 'tenant-a' }, noria_business_context: { commercial_policy: { contract: 'noria_commercial_policy_v1', tenant_id: 'tenant-a', trade_in: { accepted_subject_to_appraisal: true } } } }, null, {}, {}, {}, [], [], inquiryPlan
  );
  assert.equal(configuredPolicyLedger.official.policy.vehicle_trade_in_accepted_subject_to_appraisal, true);
  assert.ok(configuredPolicyLedger.facts.some((fact) => fact.id === 'trade_in_policy' && fact.value === 'true'));
});

